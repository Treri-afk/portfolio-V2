const REFERENCE = /\{([^}]+)\}/g;
const DARK = 'portfolio.dark';

const toCss = (value) => String(value).replace(REFERENCE, (_, path) => `var(--${path.replaceAll('.', '-')})`);

const declaration = (token) => {
  const light = toCss(token.original.$value);
  const dark = token.original.$extensions?.[DARK];
  return `  --${token.name}: ${dark ? `light-dark(${light}, ${toCss(dark)})` : light};`;
};

/*
 * Semantic colors are light-dark() pairs: color-scheme alone switches the theme.
 * --scheme-inverse lets a block (Slice tone="inverse") flip to the opposite scheme in either theme.
 */
const SCHEMES = [
  ':root { color-scheme: light dark; --scheme-inverse: dark; }',
  "@media (prefers-color-scheme: dark) { :root:not([data-theme='light']) { --scheme-inverse: light; } }",
  ":root[data-theme='light'] { color-scheme: light; --scheme-inverse: dark; }",
  ":root[data-theme='dark'] { color-scheme: dark; --scheme-inverse: light; }",
];

const isDuration = (token) => token.$type === 'duration' && !String(token.original.$value).includes('{');

export const cssFormat = ({ dictionary }) => {
  const tokens = dictionary.allTokens.filter((token) => !['breakpoint', 'image', 'responsive'].includes(token.path[0]));
  const reduced = tokens.filter(isDuration).map((token) => `    --${token.name}: 0ms;`);
  return [
    '/* Generated by @portfolio/tokens. Do not edit. */',
    ':root {',
    ...tokens.map(declaration),
    '}',
    ...SCHEMES,
    '@media (prefers-reduced-motion: reduce) {',
    '  :root {',
    ...reduced,
    '  }',
    '}',
    '',
  ].join('\n');
};

/** Motion allowed: shared by the CSS custom media and the clip player in TypeScript. */
const MOTION_OK = '(prefers-reduced-motion: no-preference)';

export const customMediaFormat = ({ dictionary }) => [
  '/* Generated by @portfolio/tokens. Do not edit. */',
  ...dictionary.allTokens
    .filter((token) => token.path[0] === 'breakpoint')
    .map((token) => `@custom-media --bp-${token.path[1]} (width >= ${token.original.$value});`),
  `@custom-media --motion-ok ${MOTION_OK};`,
  '@custom-media --hover (hover: hover) and (pointer: fine);',
  '',
].join('\n');

/** Responsive image settings for TypeScript: srcset widths, `sizes` presets and the motion query. */
export const mediaFormat = ({ dictionary }) => {
  const media = dictionary.allTokens.filter((token) => token.path[0] === 'responsive');
  const widths = media.filter((token) => token.path[1] === 'width').map((token) => Number(token.$value));
  const sizes = media.filter((token) => token.path[1] === 'sizes').map((token) => `  ${token.path[2]}: '${token.$value}',`);
  return [
    '// Generated by @portfolio/tokens. Do not edit.',
    `export const mediaWidths = [${widths.join(', ')}] as const;`,
    '',
    'export const mediaSizes = {',
    ...sizes,
    '} as const;',
    '',
    'export type MediaSizes = keyof typeof mediaSizes;',
    '',
    `export const motionOk = '${MOTION_OK}';`,
    '',
  ].join('\n');
};

/** Favicon in the site's own language: accent square cut by a slanted ink stroke. Colors come from tokens. */
export const faviconFormat = ({ dictionary }) => {
  const value = (path) => dictionary.allTokens.find((token) => token.path.join('.') === path)?.$value;
  const accent = value('color.vermillon.600');
  const ink = value('color.neutral.950');
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">',
    `  <rect width="32" height="32" fill="${accent}"/>`,
    `  <polygon points="0,20 32,12 32,18 0,26" fill="${ink}"/>`,
    '</svg>',
    '',
  ].join('\n');
};
